  // Оценка на любом шаге: подходит и для живого прогноза, и для результата этапа.
  function evaluate(answers) {
    answers = answers || {};
    const {share, count} = interestProfile(answers);
    const jobs = listAnswer(answers, 'experience').map(v => experienceOptions.find(o => o.value === v)).filter(Boolean);
    const praise = listAnswer(answers, 'praise').map(v => praiseOptions.find(o => o.value === v)).filter(Boolean);
    const styleKeys = ['people', 'calls', 'detail', 'routine', 'persistence'].filter(k => typeof answers[k] === 'number');
    const styleAnswers = Object.fromEntries(styleKeys.map(k => [k, questions.find(q => q.id === k).options[answers[k]].value]));

    const ranked = spheres.map((s, index) => {
      const fit = cosine(share, s.ria);
      const jobHit = jobs.some(j => j.spheres.includes(s.id)) ? 1 : 0;
      const praiseHits = praise.filter(p => p.spheres.includes(s.id)).length;
      const experience = Math.min(1, .6 * jobHit + .3 * praiseHits);
      const style = styleKeys.length ? styleKeys.reduce((sum, k) => sum + 1 - Math.abs(styleAnswers[k] - s.style[k]), 0) / styleKeys.length : null;
      const score = style === null ? .75 * fit + .25 * experience : .6 * fit + .2 * experience + .2 * style;
      return {id: s.id, index, score, fit, experience, style, jobHit: !!jobHit, praiseHits};
    }).sort((a, b) => b.score - a.score || b.fit - a.fit || a.index - b.index);

    const values = Object.values(share);
    const flat = count >= 6 && Math.max(...values) - Math.min(...values) < .2;
    const leading = topTypes(share, sphereById[ranked[0].id].ria);
    return {share, count, types: Object.values(share).some(v => v > 0) ? leading : [], flat, ranked, top: ranked.slice(0, 3), jobs, praise, styleAnswers};
  }

